export type UiLang = "hi" | "en";

export function uiLang(languageCode?: string | null): UiLang {
  // Hindi and Hinglish are the demo's first language. Every other language
  // keeps the plain English labels but still gets a voice reply in its own
  // language, which is what the merchant actually hears.
  return languageCode?.startsWith("hi") ? "hi" : "en";
}

